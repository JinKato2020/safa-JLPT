"""発話表現(hatsuwa)を3軸で分類＝機能(function)/場面(scene)/弁別軸(axis)。
なぜ3軸か: 発話表現のワンパターンは「機能が偏る」「弁別軸(ダミーが試す対比)が固定」で起きる。
場面(絵＋ナレで提示)は従軸=分散確認用。機能を均し弁別軸を回すのが多様化の本筋。
分類は台本＋正解＋ダミーの表層形からの自動推定＝近似(refinableな下書きタグ)。
使い方: from hatsuwa_axes import classify_item ; f,s,a = classify_item(item)
"""
import os, sys, glob, re
_mg = glob.glob(os.path.join(os.getcwd(), '**', 'merge_and_gate.py'), recursive=True)
if _mg:
    sys.path.insert(0, os.path.dirname(_mg[0]))
from merge_and_gate import strip_furi as sf

# 機能タクソノミー(発話の意図)。発話表現用=即時応答よりあいさつ/定型を含む。
FUNCTIONS = ["依頼", "申し出", "許可求め", "誘い", "質問情報", "謝罪", "お礼",
             "あいさつ定型", "注意知らせ", "報告申告"]
SCENES = ["学校", "店飲食", "病院", "公共窓口", "家訪問", "職場", "近所住まい", "交通", "屋外その他"]
AXES = ["授受方向", "申出依頼許可", "時制既遂", "敬語謙尊", "定型句選択", "視点事実", "語彙動詞"]


def _form(c):
    """1選択肢の末尾表現を型に。"""
    c = sf(c)
    # 濁音て形（飲んで/包んで/運んで/呼んで/遊んで/読んで…＋補助動詞）は「で」になる＝te 版と同義に扱う。
    for k, v in [
        ('ていただけ', '依頼謙'), ('でいただけ', '依頼謙'), ('てくださらない', '依頼謙'), ('でくださらない', '依頼謙'),
        ('てもらえ', '依頼'), ('でもらえ', '依頼'), ('てもらい', '依頼'), ('でもらい', '依頼'),
        ('てくれる', '依頼砕'), ('でくれる', '依頼砕'), ('てくれま', '依頼砕'), ('でくれま', '依頼砕'),
        ('てくれ？', '依頼砕'), ('でくれ？', '依頼砕'), ('てくれない', '依頼砕'), ('でくれない', '依頼砕'),
        ('て差し上げ', '差上'), ('で差し上げ', '差上'), ('てさしあげ', '差上'), ('でさしあげ', '差上'),
        ('お' , None),  # placeholder handled below
        ('てあげ', 'あげ'), ('であげ', 'あげ'), ('ましょうか', '申出'), ('ませんか', '誘い'), ('ない？', '誘い'),
        ('ておきました', '既遂'), ('でおきました', '既遂'), ('ておいた', '既遂'), ('でおいた', '既遂'),
        ('ておいて', '既遂'), ('でおいて', '既遂'),
        ('てもいい', '許可'), ('でもいい', '許可'), ('てよろしいですか', '許可'), ('てよろしいでしょうか', '許可'),
        ('たいんですが', '希望前置'), ('たいのですが', '希望前置'), ('たいです', '希望前置'),
        ('ありがとう', '礼'), ('助かっ', '礼'), ('助かり', '礼'), ('お世話に', '礼'),
        ('すみませんでした', '謝'), ('ごめん', '謝'), ('申し訳', '謝'),
        ('いくら', '質問'), ('どこ', '質問'), ('何時', '質問'), ('何曜日', '質問'),
        ('どう', '質問'), ('いつ', '質問'), ('どのくらい', '質問'), ('どうやって', '質問'),
        ('ください', 'ください'), ('んです', '申告'),
    ]:
        if k == 'お':
            continue
        if k in c:
            return v
    return 'その他'


GREET = ['おはよう', 'こんばん', 'こんにちは', 'お邪魔しま', '失礼しま', 'ごちそうさま', 'いただきます',
         'よろしくお願い', 'ただいま', 'おかえり', 'いらっしゃい', 'お先に失礼', '行ってきます',
         'いってきます', 'いってらっしゃい', 'さようなら', 'おやすみ', 'お世話になり',
         'つまらないもの', '召し上がって', 'ご足労', 'お時間をいただき']
INFORM = ['危ない', '落ちました', '落ちましたよ', '違うよう', '届いたみたい', 'ではないでしょうか',
          '間違って', 'ではありませんか']


def classify_function(item):
    q = item['questions'][0]; corr = sf(q['choices'][q['answerIndex']])
    f = _form(q['choices'][q['answerIndex']])
    if any(g in corr for g in GREET):
        return 'あいさつ定型'
    if f == '謝':
        return '謝罪'
    if f == '礼':
        return 'お礼'
    if f == '申出':
        return '申し出'
    if f == '誘い':
        return '誘い'
    if f == '許可':
        return '許可求め'
    if any(w in corr for w in INFORM):
        return '注意知らせ'
    if f == '質問':
        return '質問情報'
    if f in ('依頼謙', '依頼', '依頼砕', 'ください', '希望前置'):
        return '依頼'
    if f == '申告':
        return '報告申告'
    return '報告申告'


_SCENE_PATS = [
    ('病院|薬局|保険証|熱|薬|診て|検査|具合|痛い|治', '病院'),
    ('先生|授業|黒板|教科書|学校|クラス', '学校'),
    ('上司|先輩|同僚|会議|資料|取引先|部長|早退|コピー|ミス|レポート|残って|出張|打ち合わせ|会社|仕事', '職場'),
    ('引っ越|隣|近所|ごみ|大家|アパート|庭|枝|鍵|回覧|向かい|越して|水やり|植木|留守|お宅', '近所住まい'),
    ('駅|電車|バス|切符|乗り換え|新幹線|かばん|降り|忘れ物', '交通'),
    ('役所|住民票|住所|窓口|図書館|郵便|送り|切手|書類|手続き|退去|配送|取り置き|本を借り|本を返', '公共窓口'),
    ('店|レジ|試着|服|値段|レストラン|注文|店員|袋|品物|買い|色違い|返品|棚|サイズ|カメラ|ホテル|品物|お水|コーヒー', '店飲食'),
    ('お邪魔|ごちそう|友達の家|飲み物|お皿|家に遊び|家に入り', '家訪問'),
]


def classify_scene(item):
    s = sf(item['script'])
    for pat, v in _SCENE_PATS:
        if re.search(pat, s):
            return v
    return '屋外その他'


def classify_axis(item):
    q = item['questions'][0]; ai = q['answerIndex']
    cats = [_form(c) for c in q['choices']]
    dd = [cats[i] for i in range(len(cats)) if i != ai]
    corrf = classify_function(item)
    if '既遂' in dd:
        return '時制既遂'
    if '差上' in dd:
        return '敬語謙尊'
    if ('申出' in dd) and ('許可' in dd):
        return '申出依頼許可'
    if ('申出' in dd) and any(x in dd for x in ('依頼', '依頼砕', '依頼謙')):
        return '申出依頼許可'
    if 'あげ' in dd:
        return '授受方向'
    if corrf == 'あいさつ定型':
        return '定型句選択'
    if corrf == '質問情報':
        return '視点事実'
    if ('依頼' in dd or '依頼砕' in dd or '依頼謙' in dd) and ('許可' in dd):
        return '申出依頼許可'
    return '語彙動詞'


def classify_item(item):
    return classify_function(item), classify_scene(item), classify_axis(item)
