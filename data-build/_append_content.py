def furi_ok(s):
    return ("（" in s) if re.search(r"[㐀-龯]", s) else True


def merge(path, items):
    data = json.load(open(path, encoding="utf-8"))
    have = {c["id"] for c in data}
    added = 0
    for it in items:
        if it["id"] in have:
            continue
        data.append(it)
        added += 1
    json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    return data, added


def verify(data, prefix):
    ids = [c["id"] for c in data]
    issues = []
    if len(ids) != len(set(ids)):
        issues.append("重複id")
    qids = []
    for c in data:
        if not furi_ok(c.get("body", "") + c.get("title", "") + c.get("script", "")):
            issues.append(f"{c['id']}: ふりがな?")
        for q in c["questions"]:
            qids.append(q["id"])
            if len(q["choices"]) != 4 or len(set(q["choices"])) != 4:
                issues.append(f"{q['id']}: choices不正")
            if q["answerIndex"] != 0:
                issues.append(f"{q['id']}: answerIndex!=0")
            if not q.get("explain"):
                issues.append(f"{q['id']}: explain無し")
    if len(qids) != len(set(qids)):
        issues.append("重複設問id")
    by_lvl = {}
    for c in data:
        by_lvl[c["level"]] = by_lvl.get(c["level"], 0) + 1
    print(f"[{prefix}] 計{len(data)}本 設問{len(qids)}問 級別{by_lvl}")
    print(f"[{prefix}] 問題: {issues if issues else 'なし'}")


def main():
    rdata, ra = merge(RJSON, NEW_READING)
    ldata, la = merge(LJSON, NEW_LISTENING)
    print(f"追記: 読解+{ra} 聴解+{la}")
    verify(rdata, "読解")
    verify(ldata, "聴解")


if __name__ == "__main__":
    main()
